/** Maps a scanned label to the closest catalogue category. */
export function guessCategory(rawText: string, ingredientIds: string[]): string {
  const t = rawText.toLowerCase();
  if (/noodle|instant\s*noodle|hakka|chow/.test(t)) return "instant_noodles";
  if (/biscuit|cookie|cracker|khakhra|rusk/.test(t)) return "biscuits";
  if (/chocolate|cocoa|choco/.test(t)) return "chocolate";
  if (/juice|drink|beverage|soda|cola|nectar|shake|lassi/.test(t)) return "drinks";
  if (/bread|bun|pav|loaf/.test(t)) return "bread";
  if (/jam|spread|butter|ketchup|sauce|mayo/.test(t)) return "spreads";
  if (/cereal|muesli|flakes|granola|oats|poha/.test(t)) return "breakfast_cereal";
  if (/chips|namkeen|bhujia|mixture|wafer|snack|kurkure|sev/.test(t)) return "namkeen";
  if (ingredientIds.includes("cocoa_solids")) return "chocolate";
  if (ingredientIds.includes("maida")) return "biscuits";
  return "namkeen";
}
