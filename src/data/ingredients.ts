/**
 * Alias → ingredient lookup, built once. Longer aliases are checked first by
 * the parser so "refined wheat flour" wins over "wheat flour".
 */
export const ALIAS_INDEX: Map<string, Ingredient> = (() => {
  const map = new Map<string, Ingredient>();
  for (const ing of INGREDIENTS) {
    for (const alias of ing.aliases) map.set(alias.toLowerCase().trim(), ing);
    map.set(ing.id, ing);
  }
  return map;
})();

/** Aliases sorted longest-first — used for substring fallback matching. */
export const ALIASES_BY_LENGTH: { alias: string; ing: Ingredient }[] = (() => {
  const out: { alias: string; ing: Ingredient }[] = [];
  for (const ing of INGREDIENTS) {
    for (const alias of ing.aliases) out.push({ alias: alias.toLowerCase().trim(), ing });
  }
  return out.sort((a, b) => b.alias.length - a.alias.length);
})();

export function getIngredientById(id: string): Ingredient | undefined {
  return INGREDIENTS.find((i) => i.id === id);
}
